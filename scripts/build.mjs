// Builds a static, dependency-free site into dist/.
// Classic (non-module) scripts are concatenated in order because the app shares globals between files.
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = p => join(root, 'src', p);
const dist = join(root, 'dist');

import { JS_CORE, PACK_DELE } from './order.mjs';

const hash = s => createHash('sha256').update(s).digest('hex').slice(0, 10);

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
cpSync(join(root, 'public'), dist, { recursive: true });

const data = ['ccse2026', 'tr_all', 'ex_all'].map(n => readFileSync(src(`data/${n}.json`), 'utf8').trim());
const jsOf = list => list.map(f => `// ---- ${f} ----\n` + readFileSync(src(`js/${f}`), 'utf8')).join('\n');
// data packs first: their hashed names are written into the core bundle
const ccsePack = `// Apto CCSE pack: translations + explanations. Generated, do not edit.\nTR = ${data[1]};\nEX = ${data[2]};\n`;
const delePack = `// Apto DELE pack: reading and listening texts. Generated, do not edit.\n'use strict';\n` + jsOf(PACK_DELE) + '\ndeleInit();\n';
const ccseName = `ccse.${hash(ccsePack)}.js`, deleName = `dele.${hash(delePack)}.js`;
const js = `// Apto — generated by scripts/build.mjs, do not edit\n'use strict';\n`
  + `const Q = ${data[0]};\nlet TR = {}, EX = {};\n`
  + jsOf(JS_CORE).replace('__PACK_CCSE__', ccseName).replace('__PACK_DELE__', deleName).replace('__APP_VERSION__', JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version.replace(/\.0$/, ''));
const css = readFileSync(src('styles.css'), 'utf8');

const jsName = `app.${hash(js)}.js`, cssName = `styles.${hash(css)}.css`;
writeFileSync(join(dist, jsName), js);
writeFileSync(join(dist, ccseName), ccsePack);
writeFileSync(join(dist, deleName), delePack);
writeFileSync(join(dist, cssName), css);
// Static files version: changes whenever an icon/font/image changes, so browsers drop cached favicons.
const walk = d => readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]);
const pubFiles = walk(join(root, 'public')).sort();
const assetV = hash(pubFiles.map(f => readFileSync(f).toString('base64')).join());
writeFileSync(join(dist, 'index.html'), readFileSync(src('index.html'), 'utf8').replace('__JS__', jsName).replace('__CSS__', cssName).replaceAll('__V__', assetV));

// Service worker: precache the app shell; version changes whenever any asset changes.
const files = ['./', 'index.html', jsName, ccseName, deleName, cssName, ...pubFiles.map(f => f.slice(join(root, 'public').length + 1).split('\\').join('/')).filter(f => !f.startsWith('brand/') && (!/\.(txt|png)$/.test(f) || f.startsWith('icons/')))];
const version = hash(files.join() + js + ccsePack + delePack + css + assetV);
writeFileSync(join(dist, 'sw.js'), readFileSync(join(root, 'scripts/sw.template.js'), 'utf8')
  .replace('__VERSION__', version).replace('__FILES__', JSON.stringify(files)));

console.log(`Built dist/ · ${jsName} (${(js.length/1024).toFixed(0)} KB) + ${ccseName} (${(ccsePack.length/1024).toFixed(0)} KB) + ${deleName} (${(delePack.length/1024).toFixed(0)} KB) · ${cssName} · sw ${version}`);
